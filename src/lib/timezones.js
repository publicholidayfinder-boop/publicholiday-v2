export function getTimezone(countryCode) {
    return countryTimezones[countryCode] || 'UTC';
}

export function getUtcOffset(timezone) {
    try {
        const now = new Date();
        const tzDate = new Intl.DateTimeFormat('en', {
            timeZone: timezone,
            timeZoneName: 'shortOffset'
        }).formatToParts(now);
        const offsetPart = tzDate.find(p => p.type === 'timeZoneName');
        return offsetPart ? offsetPart.value : 'UTC';
    } catch {
        return 'UTC';
    }
}
